// Turns the authored curriculum JSON in src/content/curriculum/<stage>/ into one
// idempotent SQL file per stage in supabase/content/. Lessons are inserted as
// drafts; re-running updates text but never changes the published flag, so an
// admin can review and publish in the CMS.
// Usage: node scripts/build-curriculum-sql.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const contentDir = join(root, "src", "content", "curriculum");
const outputDir = join(root, "supabase", "content");

function text(value) {
  const string = String(value);
  if (string.includes("$$")) throw new Error(`"$$" is not allowed in curriculum text: ${string.slice(0, 40)}`);
  return `'${string.replaceAll("'", "''")}'`;
}
const json = (value) => `${text(JSON.stringify(value))}::jsonb`;

export function unitSql(unit) {
  const lines = [
    `-- ${unit.unit.title}`,
    "do $$",
    "declare v_course uuid; v_unit uuid; v_lesson uuid; v_question uuid;",
    "begin",
    `  insert into public.courses(stage_id,slug,title,description,published)`,
    `  values (${text(unit.stage)},${text(unit.course.slug)},${text(unit.course.title)},${text(unit.course.description)},false)`,
    `  on conflict (slug) do update set title=excluded.title, description=excluded.description returning id into v_course;`,
    `  insert into public.units(course_id,slug,title,sort_order,published)`,
    `  values (v_course,${text(unit.unit.slug)},${text(unit.unit.title)},${unit.unit.sortOrder},false)`,
    `  on conflict (course_id,slug) do update set title=excluded.title, sort_order=excluded.sort_order returning id into v_unit;`,
  ];
  for (const lesson of unit.lessons) {
    lines.push(
      "",
      `  -- ${lesson.skill}: ${lesson.title}`,
      `  insert into public.lessons(unit_id,slug,title,skill,summary,sort_order,published)`,
      `  values (v_unit,${text(lesson.slug)},${text(lesson.title)},${text(lesson.skill)},${text(lesson.summary)},${lesson.sortOrder},false)`,
      `  on conflict (slug) do update set unit_id=excluded.unit_id, title=excluded.title, skill=excluded.skill, summary=excluded.summary, sort_order=excluded.sort_order, updated_at=now() returning id into v_lesson;`,
      `  insert into public.lesson_materials(lesson_id,content) values (v_lesson,${json(lesson.material)})`,
      `  on conflict (lesson_id) do update set content=excluded.content, updated_at=now();`,
    );
    (lesson.questions ?? []).forEach((question, index) => {
      lines.push(
        `  insert into public.exercise_questions(lesson_id,slug,prompt,options,sort_order)`,
        `  values (v_lesson,${text(question.slug)},${text(question.prompt)},${json(question.options)},${index})`,
        `  on conflict (lesson_id,slug) do update set prompt=excluded.prompt, options=excluded.options, sort_order=excluded.sort_order returning id into v_question;`,
        `  insert into public.exercise_answer_keys(question_id,correct_index,explanation,evidence)`,
        `  values (v_question,${question.answer},${text(question.explanation)},${text(question.evidence ?? "")})`,
        `  on conflict (question_id) do update set correct_index=excluded.correct_index, explanation=excluded.explanation, evidence=excluded.evidence;`,
      );
    });
    (lesson.vocabulary ?? []).forEach((entry, index) => {
      lines.push(
        `  insert into public.vocabulary_entries(lesson_id,word,phonetic,meaning_vi,definition,example,sentence_prompt_vi,accepted_sentences,sort_order)`,
        `  values (v_lesson,${text(entry.word)},${text(entry.phonetic)},${text(entry.meaningVi)},${text(entry.definition)},${text(entry.example)},${text(entry.sentencePromptVi)},${json(entry.acceptedSentences)},${index})`,
        `  on conflict (lesson_id,word) do update set phonetic=excluded.phonetic, meaning_vi=excluded.meaning_vi, definition=excluded.definition, example=excluded.example, sentence_prompt_vi=excluded.sentence_prompt_vi, accepted_sentences=excluded.accepted_sentences, sort_order=excluded.sort_order;`,
      );
    });
  }
  lines.push("end $$;");
  return lines.join("\n");
}

export function readStage(stage) {
  const dir = join(contentDir, stage);
  return readdirSync(dir).filter((name) => name.endsWith(".json")).sort()
    .map((name) => JSON.parse(readFileSync(join(dir, name), "utf8")));
}

export function stageSql(stage) {
  const header = `-- Generated by scripts/build-curriculum-sql.mjs from src/content/curriculum/${stage}. Do not edit by hand.\n-- Original IeltsWithHarry content. Lessons are created as drafts; publish them in the admin CMS.\n`;
  return `${header}\n${readStage(stage).map(unitSql).join("\n\n")}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(outputDir, { recursive: true });
  for (const stage of readdirSync(contentDir)) {
    const file = join(outputDir, `${stage}.sql`);
    writeFileSync(file, stageSql(stage));
    console.log(`wrote ${file}`);
  }
}
